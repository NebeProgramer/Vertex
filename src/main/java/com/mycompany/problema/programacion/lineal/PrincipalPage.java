    /**
     * Comprueba si el problema tiene estructura de asignación (húngaro).
     * Requisitos: - Las variables deben tener subíndice de longitud par (ej:
     * "ij" => length%2==0), se divide en 2 partes iguales (i, j). - Deben
     * existir restricciones igualdad (=) con RHS = 1 que correspondan a cada i
     * (fila) y cada j (columna), es decir: sum_j x_ij = 1 y sum_i x_ij = 1.
     */
    private boolean checkHungaro(String[] restricciones, String FO, int metodo) {
        Pattern varPattern = Pattern.compile("x(\\d+)", Pattern.CASE_INSENSITIVE);

        Matcher mFO = varPattern.matcher(FO);
        if (!mFO.find()) {
            return metodo != 0 ? pair(metodo, FO, restricciones) : false;
        }

        int idxLen = mFO.group(1).length();
        if (idxLen % 2 != 0) {
            return metodo != 0 ? pair(metodo, FO, restricciones) : false;
        }

        int subLen = idxLen / 2;
        Set<String> firstSet = new HashSet<>();
        Set<String> secondSet = new HashSet<>();
        mFO = varPattern.matcher(FO);
        while (mFO.find()) {
            String digits = mFO.group(1);
            if (digits.length() != idxLen) {
                return metodo != 0 ? pair(metodo, FO, restricciones) : false;
            }
            firstSet.add(digits.substring(0, subLen));
            secondSet.add(digits.substring(subLen));
        }

        // buscar restricciones tipo "xij + ... = 1"
        Set<String> foundRows = new HashSet<>();
        Set<String> foundCols = new HashSet<>();
        Pattern termPattern = Pattern.compile("([+-]?\\d*\\.?\\d*)x(\\d+)", Pattern.CASE_INSENSITIVE);

        for (String r : restricciones) {
            String[] partes = parseRestriction(r);
            String lhs = partes[0], op = partes[1], rhs = partes[2];

            if (!op.equals("=") || !rhs.equals("1")) {
                continue;
            }

            Matcher tm = termPattern.matcher(lhs);
            Set<String> rowIdxs = new HashSet<>();
            Set<String> colIdxs = new HashSet<>();
            boolean allCoeffsOne = true;

            while (tm.find()) {
                String coefStr = tm.group(1);
                String digits = tm.group(2);
                if (digits.length() != idxLen) {
                    allCoeffsOne = false;
                    break;
                }

                if (!(coefStr == null || coefStr.isEmpty() || coefStr.equals("+"))) {
                    try {
                        if (Math.abs(Double.parseDouble(coefStr) - 1.0) > 1e-9) {
                            allCoeffsOne = false;
                            break;
                        }
                    } catch (NumberFormatException ex) {
                        allCoeffsOne = false;
                        break;
                    }
                }

                rowIdxs.add(digits.substring(0, subLen));
                colIdxs.add(digits.substring(subLen));
            }

            if (!allCoeffsOne) {
                continue;
            }
            if (rowIdxs.size() == 1) {
                foundRows.addAll(rowIdxs);
            }
            if (colIdxs.size() == 1) {
                foundCols.addAll(colIdxs);
            }
        }

        boolean ok = foundRows.containsAll(firstSet) && foundCols.containsAll(secondSet);
        if (!ok && metodo != 0) {
            return pair(metodo, FO, restricciones);
        }

        return ok;
    }

    /**
     * Comprueba estructura de transporte / costos duales. Requisitos básicos
     * (heurísticos): - Variables xij con índice divisible en i,j (igual que
     * Hungaro). - Deben existir restricciones por cada origen (i) con RHS=num
     * (oferta) y por cada destino (j) con RHS=num (demanda). - suma(oferta) ==
     * suma(demanda).
     */
    private boolean checkCostosDuales(String[] restricciones, String FO, int metodo) {
        Pattern varPattern = Pattern.compile("x(\\d+)", Pattern.CASE_INSENSITIVE);

        Matcher mFO = varPattern.matcher(FO);
        if (!mFO.find()) {
            return false;
        }
        int idxLen = mFO.group(1).length();
        if (idxLen % 2 != 0) {
            return false; // debe dividirse en i y j
        }
        int subLen = idxLen / 2;

        // obtener sets de i y j desde FO
        Set<String> firstSet = new HashSet<>();
        Set<String> secondSet = new HashSet<>();
        mFO.reset();
        while (mFO.find()) {
            String digits = mFO.group(1);
            if (digits.length() != idxLen) {
                return false;
            }
            String a = digits.substring(0, subLen);
            String b = digits.substring(subLen);
            firstSet.add(a);
            secondSet.add(b);
        }

        // recorrer restricciones y clasificar como oferta (por i) o demanda (por j)
        Map<String, Double> oferta = new HashMap<>();
        Map<String, Double> demanda = new HashMap<>();
        Pattern termPattern = Pattern.compile("([+-]?\\d*\\.?\\d*)x(\\d+)", Pattern.CASE_INSENSITIVE);

        for (String r : restricciones) {
            String[] partes = parseRestriction(r);
            String lhs = partes[0];
            String op = partes[1];
            String rhs = partes[2];

            double rhsVal;
            try {
                rhsVal = Double.parseDouble(rhs);
            } catch (NumberFormatException ex) {
                continue;
            }

            Matcher tm = termPattern.matcher(lhs);
            Set<String> rowIdxs = new HashSet<>();
            Set<String> colIdxs = new HashSet<>();
            while (tm.find()) {
                String digits = tm.group(2);
                if (digits.length() != idxLen) {
                    rowIdxs.clear();
                    colIdxs.clear();
                    break;
                }
                String a = digits.substring(0, subLen);
                String b = digits.substring(subLen);
                rowIdxs.add(a);
                colIdxs.add(b);
            }

            if (rowIdxs.size() == 1 && colIdxs.size() >= 1 && (op.equals("<=") || op.equals("="))) {
                oferta.put(rowIdxs.iterator().next(), rhsVal);
            } else if (colIdxs.size() == 1 && rowIdxs.size() >= 1 && op.equals("=")) {
                demanda.put(colIdxs.iterator().next(), rhsVal);
            }
        }

        if (!oferta.keySet().containsAll(firstSet)) {
            return false;
        }
        if (!demanda.keySet().containsAll(secondSet)) {
            return false;
        }

        double sumOferta = oferta.values().stream().mapToDouble(Double::doubleValue).sum();
        double sumDemanda = demanda.values().stream().mapToDouble(Double::doubleValue).sum();

        // balancear si está en modo "seleccionado"
        if (metodo != 0 && Math.abs(sumOferta - sumDemanda) > 1e-9) {
            List<String> RArreglado = new ArrayList<>(Arrays.asList(restricciones));
            String nuevaFO = FO;

            if (sumOferta > sumDemanda) {
                double faltante = sumOferta - sumDemanda;
                String nuevaCol = "DF"; // demanda ficticia
                for (String fila : firstSet) {
                    String var = "x" + fila + nuevaCol;
                    nuevaFO = nuevaFO + " + 0" + var;
                }
                RArreglado.add("Σx_" + nuevaCol + " = " + faltante);
            } else {
                double faltante = sumDemanda - sumOferta;
                String nuevaFila = "OF"; // oferta ficticia
                for (String col : secondSet) {
                    String var = "x" + nuevaFila + col;
                    nuevaFO = nuevaFO + " + 0" + var;
                }
                RArreglado.add("Σx_" + nuevaFila + " = " + faltante);
            }

            setFO(nuevaFO);
            setR(RArreglado.toArray(new String[0]));
            return pair(metodo, nuevaFO, getR());
        }

        return Math.abs(sumOferta - sumDemanda) < 1e-9;
    }

    /**
     * Heurístico para detectar caso candidato a Dual Simplex. Actualmente: si
     * existe alguna restricción con RHS < 0 -> sugerir Dual Simplex. (Es un
     * heurístico simple; podemos mejorar con análisis de tabla inicial,
     * factibilidad, etc.)
     */
    private boolean checkDualSimplex(String[] restricciones, String FO, int metodo) {
    boolean hayNegativo = false;
    for (String r : restricciones) {
        String[] partes = parseRestriction(r); // [lhs, op, rhs]
        String rhs = partes[2];
        try {
            double val = Double.parseDouble(rhs);
            if (val < 0) {
                hayNegativo = true;
                break;
            }
        } catch (NumberFormatException ex) {
            // ignorar no numéricos
        }
    }

    if (metodo != 0) {
        return pair(metodo, FO, restricciones);
    }

    return hayNegativo; // heurístico: si hay RHS < 0 → sugerir Dual Simplex
}


// 4. Método Gráfico
    private boolean checkGrafico(String[] restricciones, String FO, int metodo) {
        // El método gráfico solo exige 2 variables de decisión. A diferencia
        // de Simplex/Big-M/Dual/etc, NO necesita transformar la FO ni las
        // restricciones (no usa holguras, excesos ni artificiales) porque
        // evalúa cada restricción tal cual (<=, >= o =) al validar los
        // vértices — por eso NO debe llamar a pair(), que no tiene un caso
        // para este método y por eso siempre devolvía false al elegirlo
        // manualmente. Tampoco debe descartar >= ni =, porque el gráfico
        // los soporta perfectamente (a diferencia de Big-M, que sí los
        // necesita para decidir si aplica).
        Pattern varPattern = Pattern.compile("x(\\d+)", Pattern.CASE_INSENSITIVE);
        Matcher m = varPattern.matcher(FO);
        Set<Integer> vars = new HashSet<>();
        while (m.find()) {
            vars.add(Integer.valueOf(m.group(1)));
        }
        return vars.size() == 2;
    }

    private boolean isZero(String s) {
        try {
            return Math.abs(Double.parseDouble(s.trim())) < 1e-9;
        } catch (NumberFormatException e) {
            return false;
        }
    }

// 5. Método Big-M
private boolean checkBigM(String[] restricciones, String FO, int metodo) {
    // Condición: restricciones con ≥ o = y RHS ≠ 0 → necesita artificiales
    for (String r : restricciones) {
        if (r.contains(">=") || (r.contains("=") && !r.trim().endsWith("0"))) {
            if (metodo == 0) {
                return true; // heurístico
            } else {
                return pair(metodo, FO, restricciones);
            }
        }
    }
    if (metodo != 0) {
        return pair(metodo, FO, restricciones);
    }
    return false;
}


// 6. Método Simplex Estándar
    private boolean checkSimplex(String[] restricciones, String FO, int metodo) {
        // Siempre válido, es el "catch-all"
        if (metodo != 0) {
            return pair(metodo, FO, restricciones);
        }
        return true;
    }

private boolean pair(int metodo, String FO, String[] R) {
    List<String> RArreglado;
    String nuevaFO;
    Pattern varPattern;
    Matcher mFO;
    int subLen;

    switch (metodo) {
        case 3: // Simplex: agregar holguras/excesos (y añadirlas a FO con coef 0)
            List<String> nuevasRestricciones = new ArrayList<>();
            String nuevaFOSB1 = FO == null ? "" : FO.trim();
            int holguraCount = 0;
            int excesoCount = 0;

            for (String r : R) {
                String[] partes = parseRestriction(r);
                String lhs = partes[0].trim();
                String op  = partes[1].trim();
                String rhs = partes[2].trim();

                if (op.equals("<=")) {
                    holguraCount++;
                    String sVar = "S" + holguraCount;
                    nuevasRestricciones.add(lhs + " + " + sVar + " = " + rhs);
                    nuevaFOSB1 = addZeroVarToFO(nuevaFOSB1, sVar);
                } else if (op.equals(">=")) {
                    excesoCount++;
                    String eVar = "E" + excesoCount;
                    nuevasRestricciones.add(lhs + " - " + eVar + " = " + rhs);
                    nuevaFOSB1 = addZeroVarToFO(nuevaFOSB1, eVar);
                } else { // '='
                    nuevasRestricciones.add(lhs + " = " + rhs);
                }
            }

            setR(nuevasRestricciones.toArray(new String[0]));
            setFO(nuevaFOSB1);
            return true;

        case 4: // Big-M: agregar artificiales y penalizarlas en FO con M*(A#)
            nuevasRestricciones = new ArrayList<>();
            StringBuilder nuevaFOSB = new StringBuilder(FO == null ? "" : FO.trim());
            int artificialCount = 0;

            for (String r : R) {
                String[] partes = parseRestriction(r);
                String lhs = partes[0].trim();
                String op  = partes[1].trim();
                String rhs = partes[2].trim();

                if (op.equals(">=") || (op.equals("=") && !isZero(rhs))) {
                    artificialCount++;
                    String artVar = "A" + artificialCount;
                    // Para >=: normalmente harías "- e + a = rhs", pero para simplificar
                    // convertimos a igualdad con artificial y (opcional) exceso
                    // Aquí agregamos la artificial directamente:
                    nuevasRestricciones.add(lhs + " + " + artVar + " = " + rhs);
                    // penalizar en FO: usar M*ArtVar (agrega como + M*A# ; si usas max/min, ajusta signo)
                    nuevaFOSB.append(" + M*").append(artVar);
                } else {
                    nuevasRestricciones.add(lhs + " " + op + " " + rhs);
                }
            }

            setR(nuevasRestricciones.toArray(new String[0]));
            setFO(nuevaFOSB.toString());
            return true;

        case 5: // Dual Simplex: invertir restricciones con RHS < 0 (negar LHS y RHS, invertir op)
            nuevasRestricciones = new ArrayList<>();
            for (String r : R) {
                String[] partes = parseRestriction(r);
                String lhs = partes[0].trim();
                String op  = partes[1].trim();
                String rhs = partes[2].trim();

                double val;
                try {
                    val = Double.parseDouble(rhs);
                } catch (NumberFormatException ex) {
                    nuevasRestricciones.add(lhs + " " + op + " " + rhs);
                    continue;
                }

                if (val < 0) {
                    String nuevoOp;
                    if (op.equals("<=")) nuevoOp = ">=";
                    else if (op.equals(">=")) nuevoOp = "<=";
                    else nuevoOp = op;

                    String nuevoLHS = negateLHS(lhs);
                    String nuevoRHS = String.valueOf(-val);
                    nuevasRestricciones.add(nuevoLHS + " " + nuevoOp + " " + nuevoRHS);
                } else {
                    nuevasRestricciones.add(lhs + " " + op + " " + rhs);
                }
            }
            setR(nuevasRestricciones.toArray(new String[0]));
            setFO(FO);
            return true;

        case 6: // Costos Dual: balancear oferta/demanda creando INDICES NUMÉRICOS nuevos
            // reconstruimos oferta/demanda igual que en check y, si hay diferencia, agregamos columnas/filas numericas
            varPattern = Pattern.compile("x(\\d+)", Pattern.CASE_INSENSITIVE);
            mFO = varPattern.matcher(FO);
            if (!mFO.find()) return false;
            int idxLen = mFO.group(1).length();
            if (idxLen % 2 != 0) return false;
            subLen = idxLen / 2;

            // obtener sets de i y j desde FO
            Set<String> firstSet = new LinkedHashSet<>();
            Set<String> secondSet = new LinkedHashSet<>();
            mFO.reset();
            while (mFO.find()) {
                String digits = mFO.group(1);
                if (digits.length() != idxLen) return false;
                String a = digits.substring(0, subLen);
                String b = digits.substring(subLen);
                firstSet.add(a); secondSet.add(b);
            }

            // armar mapas oferta/demanda
            Map<String, Double> oferta = new LinkedHashMap<>();
            Map<String, Double> demanda = new LinkedHashMap<>();
            Pattern termPattern = Pattern.compile("([+-]?\\d*\\.?\\d*)x(\\d+)", Pattern.CASE_INSENSITIVE);
            for (String r : R) {
                String[] partes = parseRestriction(r);
                String lhs = partes[0]; String op = partes[1]; String rhs = partes[2];
                double rhsVal;
                try { rhsVal = Double.parseDouble(rhs); } catch (NumberFormatException ex) { continue; }

                Matcher tm = termPattern.matcher(lhs);
                Set<String> rowIdxs = new HashSet<>(), colIdxs = new HashSet<>();
                while (tm.find()) {
                    String digits = tm.group(2);
                    if (digits.length() != idxLen) { rowIdxs.clear(); colIdxs.clear(); break; }
                    String a = digits.substring(0, subLen), b = digits.substring(subLen);
                    rowIdxs.add(a); colIdxs.add(b);
                }
                if (rowIdxs.size() == 1 && colIdxs.size() >= 1 && (op.equals("<=") || op.equals("="))) {
                    oferta.put(rowIdxs.iterator().next(), rhsVal);
                } else if (colIdxs.size() == 1 && rowIdxs.size() >= 1 && op.equals("=")) {
                    demanda.put(colIdxs.iterator().next(), rhsVal);
                }
            }

            if (!oferta.keySet().containsAll(firstSet) || !demanda.keySet().containsAll(secondSet)) {
                return false;
            }

            double sumOferta = oferta.values().stream().mapToDouble(Double::doubleValue).sum();
            double sumDemanda = demanda.values().stream().mapToDouble(Double::doubleValue).sum();
            if (Math.abs(sumOferta - sumDemanda) < 1e-9) return true;

            // decidir índices nuevos: usamos la mayor fila/col existente + k
            int[] maxRC = getMaxRowCol(FO);
            int maxRow = maxRC[0], maxCol = maxRC[1];

            RArreglado = new ArrayList<>(Arrays.asList(R));
            nuevaFO = FO;

            if (sumOferta > sumDemanda) {
                double faltante = sumOferta - sumDemanda;
                // crear 1 nueva columna con index = maxCol+1
                int newCol = maxCol + 1;
                String newColStr = String.format("%0" + (idxLen/2) + "d", newCol);
                for (String fila : firstSet) {
                    String varDigits = fila + newColStr;
                    String var = "x" + varDigits;
                    nuevaFO = addZeroVarToFO(nuevaFO, var);
                }
                // crear restriccion de la nueva columna: suma_i x(i,newCol)=faltante
                StringBuilder sb = new StringBuilder();
                boolean first = true;
                for (String fila : firstSet) {
                    if (!first) sb.append(" + ");
                    sb.append("x").append(fila).append(newColStr);
                    first = false;
                }
                sb.append(" = ").append(String.valueOf((long)faltante));
                RArreglado.add(sb.toString());
            } else {
                double faltante = sumDemanda - sumOferta;
                // crear 1 nueva fila con index = maxRow+1
                int newRow = maxRow + 1;
                String newRowStr = String.format("%0" + (idxLen/2) + "d", newRow);
                for (String col : secondSet) {
                    String varDigits = newRowStr + col;
                    String var = "x" + varDigits;
                    nuevaFO = addZeroVarToFO(nuevaFO, var);
                }
                // restricción de la nueva fila: suma_j x(newRow,j) = faltante
                StringBuilder sb = new StringBuilder();
                boolean first = true;
                for (String col : secondSet) {
                    if (!first) sb.append(" + ");
                    sb.append("x").append(newRowStr).append(col);
                    first = false;
                }
                sb.append(" = ").append(String.valueOf((long)faltante));
                RArreglado.add(sb.toString());
            }

            setFO(nuevaFO);
            setR(RArreglado.toArray(new String[0]));
            return true;

        case 7: // Hungaro: asegurar indices numéricos y crear columnas/filas numéricas
            varPattern = Pattern.compile("x(\\d+)", Pattern.CASE_INSENSITIVE);
            mFO = varPattern.matcher(FO);
            if (!mFO.find()) return false;
            int idx = mFO.group(1).length();
            if (idx % 2 != 0) return false; // no se puede dividir

            // recolectar sets
            Set<String> filas = new LinkedHashSet<>();
            Set<String> cols = new LinkedHashSet<>();
            mFO.reset();
            while (mFO.find()) {
                String subIndice = mFO.group(1);
                int subL = subIndice.length()/2;
                filas.add(subIndice.substring(0, subL));
                cols.add(subIndice.substring(subL));
            }

            int difer = filas.size() - cols.size();
            if (difer == 0) return true;

            // decidir max indices
            int[] maxRC2 = getMaxRowCol(FO);
            int maxR = maxRC2[0], maxC = maxRC2[1];
            RArreglado = new ArrayList<>(Arrays.asList(R));
            nuevaFO = FO;

            if (difer > 0) {
                // agregar columnas numéricas: maxC+1 ... maxC+difer
                for (int k = 1; k <= difer; k++) {
                    int newCol = maxC + k;
                    String newColStr = String.format("%0" + (idx/2) + "d", newCol);
                    for (String fila : filas) {
                        String var = "x" + fila + newColStr;
                        nuevaFO = addZeroVarToFO(nuevaFO, var);
                    }
                    // agregar restricción columna (sum_i x(i,newCol)=1)
                    StringBuilder sb = new StringBuilder();
                    boolean first = true;
                    for (String fila : filas) {
                        if (!first) sb.append(" + ");
                        sb.append("x").append(fila).append(newColStr);
                        first = false;
                    }
                    sb.append(" = 1");
                    RArreglado.add(sb.toString());
                }
            } else {
                // agregar filas numéricas
                int need = -difer;
                for (int k = 1; k <= need; k++) {
                    int newRow = maxR + k;
                    String newRowStr = String.format("%0" + (idx/2) + "d", newRow);
                    for (String col : cols) {
                        String var = "x" + newRowStr + col;
                        nuevaFO = addZeroVarToFO(nuevaFO, var);
                    }
                    // agregar restricción fila (sum_j x(newRow,j)=1)
                    StringBuilder sb = new StringBuilder();
                    boolean first = true;
                    for (String col : cols) {
                        if (!first) sb.append(" + ");
                        sb.append("x").append(newRowStr).append(col);
                        first = false;
                    }
                    sb.append(" = 1");
                    RArreglado.add(sb.toString());
                }
            }

            setFO(nuevaFO);
            setR(RArreglado.toArray(new String[0]));
            return true;

        default:
            return false;
    }
}

    
    // Devuelve el par (maxFilaIndex, maxColIndex) leyendo subíndices numéricos x(ij)
private int[] getMaxRowCol(String FO) {
    Pattern varPattern = Pattern.compile("x(\\d+)");
    Matcher m = varPattern.matcher(FO);
    int idxLen = -1;
    Set<String> filas = new HashSet<>(), cols = new HashSet<>();
    while (m.find()) {
        String digits = m.group(1);
        if (idxLen == -1) idxLen = digits.length();
        if (digits.length() != idxLen) continue;
        int subLen = idxLen/2;
        String a = digits.substring(0, subLen);
        String b = digits.substring(subLen);
        filas.add(a); cols.add(b);
    }
    int maxRow = filas.stream().mapToInt(s -> Integer.parseInt(s)).max().orElse(0);
    int maxCol = cols.stream().mapToInt(s -> Integer.parseInt(s)).max().orElse(0);
    return new int[]{maxRow, maxCol, (idxLen==-1?0:idxLen)};
}

// Convierte un LHS en su negado: cambia signos de términos de forma segura.
// Ej: "3x11 - x12 + 5x13" -> "-3x11 + x12 - 5x13"
private String negateLHS(String lhs) {
    // añadir + delante si no tiene signo para facilitar reemplazos
    lhs = lhs.trim();
    if (lhs.length()==0) return lhs;
    if (!(lhs.charAt(0)=='+' || lhs.charAt(0)=='-')) lhs = "+" + lhs;
    // swap '+' and '-' safely
    lhs = lhs.replace("+", "##PLUS##");
    lhs = lhs.replace("-", "+");
    lhs = lhs.replace("##PLUS##", "-");
    // cleanup spaces
    return lhs.replaceAll("\\s+", " ").trim();
}

// Añade variable a FO con coef 0 (evita problemas de parseo)
private String addZeroVarToFO(String FO, String varName) {
    FO = (FO == null) ? "" : FO.trim();
    if (!FO.endsWith(" ") && FO.length()>0) FO += " ";
    // ejemplo: "+ 0x123"
    return FO + "+ 0" + varName;
}


