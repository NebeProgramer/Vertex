    public static String[][] validateAndBuild(String FO, String[] R) {
        if (FO == null || FO.trim().isEmpty() || R == null || R.length == 0) {
            throw new IllegalArgumentException("La función objetivo y las restricciones no pueden estar vacías.");
        }

        FO = FO.replaceAll("\\s+", "");
        for (int i = 0; i < R.length; i++) {
            R[i] = R[i].replaceAll("\\s+", "");
        }

        // Detectar variables en FO
        Pattern varPattern = Pattern.compile("x(\\d+)", Pattern.CASE_INSENSITIVE);
        Set<Integer> foVars = new HashSet<>();
        Set<Integer> restrVars = new HashSet<>();
        Set<Integer> formatos = new HashSet<>();

        Matcher mFO = varPattern.matcher(FO);
        while (mFO.find()) {
            foVars.add(Integer.valueOf(mFO.group(1)));
            formatos.add(mFO.group(1).length());
        }

        for (String restr : R) {
            Matcher mR = varPattern.matcher(restr);
            while (mR.find()) {
                restrVars.add(Integer.valueOf(mR.group(1)));
                formatos.add(mR.group(1).length());
            }
        }

        if (formatos.size() > 1) {
            throw new IllegalArgumentException("Inconsistencia en las variables: mezcla de índices con distinta longitud.");
        }

        // Variables definidas por FO (todas deben aparecer en FO)
        List<Integer> orderedVars = new ArrayList<>(foVars);
        Collections.sort(orderedVars);

        // Validar que ninguna restricción use variables fuera de FO
        for (int var : restrVars) {
            if (!foVars.contains(var)) {
                throw new IllegalArgumentException("Variable x" + var + " aparece en restricciones pero no en FO.");
            }
        }

        int Xn = orderedVars.size();
        String[][] RMat = new String[R.length][Xn + 2];

        // Procesar restricciones
        for (int i = 0; i < R.length; i++) {
            String restr = R[i];

            // Validar un operador
            Pattern opPattern = Pattern.compile("(<=|>=|=|<|>)");
            Matcher mOp = opPattern.matcher(restr);
            int count = 0;
            while (mOp.find()) {
                count++;
            }
            if (count != 1) {
                throw new IllegalArgumentException("La restricción " + (i + 1) + " no tiene exactamente un operador.");
            }

            // Dividir restricción
            String[] partes = parseRestriction(restr);
            String lhs = partes[0];
            String op = partes[1];
            String rhs = partes[2];

            // Validar RHS
            if (!rhs.matches("-?\\d+(\\.\\d+)?")) {
                throw new IllegalArgumentException("La restricción " + (i + 1) + " tiene un término independiente no numérico: " + rhs);
            }

            // Parsear coeficientes → mapa
            Map<Integer, String> coeffs = parseCoefficientsMap(lhs);

            // Rellenar fila
            for (int j = 0; j < Xn; j++) {
                int varIndex = orderedVars.get(j);
                RMat[i][j] = coeffs.getOrDefault(varIndex, "0");
            }
            RMat[i][Xn] = op;
            RMat[i][Xn + 1] = rhs;
        }

        return RMat;
    }

// Divide restricción en LHS, operador, RHS
    public static String[] parseRestriction(String restr) {
        return ParserLP.partirRestriccion(restr);
    }

// Convierte LHS en vector de coeficientes
    public static String[] parseCoefficients(String lhs, int Xn) {
        String[] coeffs = new String[Xn];
        Arrays.fill(coeffs, "0");
        Map<Integer, Double> parsed = ParserLP.parsearTerminos(lhs);
        for (Map.Entry<Integer, Double> e : parsed.entrySet()) {
            int index = e.getKey() - 1; // x1 → columna 0
            if (index >= 0 && index < Xn) {
                coeffs[index] = fmtCoef(e.getValue());
            }
        }
        return coeffs;
    }

    private static String fmtCoef(double v) {
        if (Math.abs(v - Math.round(v)) < 1e-9) {
            return String.valueOf(Math.round(v));
        }
        return String.valueOf(v);
    }

    public static Map<Integer, String> parseCoefficientsMap(String lhs) {
        Map<Integer, Double> parsed = ParserLP.parsearTerminos(lhs);
        Map<Integer, String> coeffs = new HashMap<>();
        for (Map.Entry<Integer, Double> e : parsed.entrySet()) {
            coeffs.put(e.getKey(), fmtCoef(e.getValue()));
        }
        return coeffs;
    }

