    /**
     * Resuelve el problema con el método Simplex estándar (todas las
     * restricciones deben ser de tipo <= con término independiente >= 0;
     * para otros casos usar Big M o Simplex Dual).
     *
     * @param FO   función objetivo, ej: "3x1+5x2"
     * @param R    restricciones, ej: {"x1<=4", "2x2<=12", "3x1+2x2<=18"}
     * @param tipo "Max" o "Min"
     */
    public void calculos(String FO, String[] R, String tipo) {
        ParserLP.validarVariablesCompletas(FO, R);
        tableros.clear();
        basisHistory.clear();
        pasoInfo.clear();
        pivotRowHistory.clear();
        pivotColHistory.clear();
        pasoActual = 0;
        esMin = tipo != null && tipo.trim().equalsIgnoreCase("Min");

        String foLimpia = FO.replaceAll("\\s+", "");

        // 1. Detectar variables de decisión (x1, x2, ...) en la FO
        Pattern varPattern = Pattern.compile("x(\\d+)", Pattern.CASE_INSENSITIVE);
        TreeSet<Integer> idxs = new TreeSet<>();
        Matcher mfo = varPattern.matcher(foLimpia);
        while (mfo.find()) {
            idxs.add(Integer.parseInt(mfo.group(1)));
        }
        if (idxs.isEmpty()) {
            throw new IllegalArgumentException("No se encontraron variables (x1, x2, ...) en la función objetivo.");
        }

        List<Integer> ordered = new ArrayList<>(idxs);
        numVars = ordered.size();

        Map<Integer, String> foCoefs = PrincipalPage.parseCoefficientsMap(foLimpia);
        double[] c = new double[numVars];
        for (int k = 0; k < numVars; k++) {
            c[k] = parseNum(foCoefs.getOrDefault(ordered.get(k), "0"));
        }

        // 2. Parsear restricciones -> A x <= b  (solo <=, RHS >= 0)
        int m = R.length;
        numSlack = m;
        double[][] A = new double[m][numVars];
        double[] b = new double[m];

        for (int i = 0; i < m; i++) {
            String[] partes = PrincipalPage.parseRestriction(R[i]);
            String lhs = partes[0];
            String op = partes[1];
            String rhs = partes[2];

            if (!"<=".equals(op)) {
                throw new IllegalArgumentException(
                        "El método Simplex estándar solo admite restricciones de tipo <=.\n"
                        + "La restricción " + (i + 1) + " (\"" + R[i] + "\") usa '" + op + "'.\n"
                        + "Prueba con Big M o Simplex Dual para este caso.");
            }

            double rhsVal = parseNum(rhs);
            if (rhsVal < 0) {
                throw new IllegalArgumentException(
                        "La restricción " + (i + 1) + " tiene término independiente negativo.\n"
                        + "Prueba con Simplex Dual para este caso.");
            }
            b[i] = rhsVal;

            Map<Integer, String> coefs = PrincipalPage.parseCoefficientsMap(lhs);
            for (int k = 0; k < numVars; k++) {
                A[i][k] = parseNum(coefs.getOrDefault(ordered.get(k), "0"));
            }
        }

        varNames = new String[numVars + numSlack];
        for (int k = 0; k < numVars; k++) {
            varNames[k] = mapeo.nombreDe(ordered.get(k));
        }
        for (int i = 0; i < numSlack; i++) {
            varNames[numVars + i] = "s" + (i + 1); // holgura de la restricción i (como en los apuntes)
        }

        // 3. Construir tabla inicial: [A | I | b] y fila Z = -c
        int totalCols = numVars + numSlack + 1;
        double[][] T = new double[m + 1][totalCols];
        for (int i = 0; i < m; i++) {
            for (int k = 0; k < numVars; k++) {
                T[i][k] = A[i][k];
            }
            T[i][numVars + i] = 1.0;
            T[i][totalCols - 1] = b[i];
        }

        // Internamente siempre se maximiza; si es Min, se maximiza -c y al final se niega Z.
        for (int k = 0; k < numVars; k++) {
            double cInterno = esMin ? -c[k] : c[k];
            T[m][k] = -cInterno;
        }
        // columnas de holgura y RHS de la fila Z quedan en 0

        int[] basis = new int[m];
        for (int i = 0; i < m; i++) {
            basis[i] = numVars + i; // basis inicial = variables de holgura
        }

        guardarPaso(T, basis, "Tablero inicial (base: holguras)", -1, -1);

        // 4. Iterar
        int iterMax = 200;
        int iter = 0;
        while (iter++ < iterMax) {
            // columna pivote: coeficiente más negativo de la fila Z
            int pivotCol = -1;
            double masNegativo = -1e-9;
            for (int j = 0; j < numVars + numSlack; j++) {
                if (T[m][j] < masNegativo) {
                    masNegativo = T[m][j];
                    pivotCol = j;
                }
            }
            if (pivotCol == -1) {
                break; // óptimo alcanzado
            }

            // prueba de la razón mínima
            int pivotRow = -1;
            double mejorRatio = Double.MAX_VALUE;
            for (int i = 0; i < m; i++) {
                if (T[i][pivotCol] > 1e-9) {
                    double ratio = T[i][totalCols - 1] / T[i][pivotCol];
                    if (ratio < mejorRatio - 1e-9) {
                        mejorRatio = ratio;
                        pivotRow = i;
                    }
                }
            }
            if (pivotRow == -1) {
                throw new IllegalArgumentException("El problema no tiene solución acotada (unbounded).");
            }

            String entra = varNames[pivotCol];
            String sale = varNames[basis[pivotRow]];

            // pivoteo (Gauss-Jordan)
            double pivotVal = T[pivotRow][pivotCol];
            for (int j = 0; j < totalCols; j++) {
                T[pivotRow][j] /= pivotVal;
            }
            for (int i = 0; i <= m; i++) {
                if (i == pivotRow) {
                    continue;
                }
                double factor = T[i][pivotCol];
                if (Math.abs(factor) > 1e-12) {
                    for (int j = 0; j < totalCols; j++) {
                        T[i][j] -= factor * T[pivotRow][j];
                    }
                }
            }

            basis[pivotRow] = pivotCol;
            guardarPaso(T, basis, "Entra " + entra + ", sale " + sale + " (fila pivote " + (pivotRow + 1) + ")", pivotRow, pivotCol);
        }

        // 5. Extraer solución de la última tabla
        solucion = new double[numVars];
        for (int i = 0; i < m; i++) {
            if (basis[i] < numVars) {
                solucion[basis[i]] = T[i][totalCols - 1];
            }
        }
        double zRow = T[m][totalCols - 1];
        zOptimo = esMin ? -zRow : zRow;

        // datos para el análisis de sensibilidad (base óptima en forma estándar)
        sensC = c;
        sensA = A;
        sensB = b;
        sensBase = basis.clone();

        StringBuilder sb = new StringBuilder();
        sb.append("Solución óptima: \n");
        for (int k = 0; k < numVars; k++) {
            sb.append(varNames[k]).append(" = ").append(fmt(solucion[k])).append("\n");
        }
        sb.append("Z = ").append(fmt(zOptimo));
        resultadoTexto = sb.toString();

        mostrarPaso(0);
    }

